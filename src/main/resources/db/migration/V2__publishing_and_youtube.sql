CREATE TABLE youtube_credential (
    id                      INTEGER PRIMARY KEY,
    encrypted_refresh_token TEXT                     NOT NULL,
    connected_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked                 BOOLEAN                  NOT NULL DEFAULT FALSE,
    last_error              TEXT,
    CONSTRAINT youtube_credential_singleton CHECK (id = 1)
);

CREATE TABLE channel_settings (
    id             INTEGER PRIMARY KEY,
    channel_handle VARCHAR(100) NOT NULL DEFAULT '',
    privacy_status VARCHAR(20)  NOT NULL DEFAULT 'public',
    CONSTRAINT channel_settings_singleton CHECK (id = 1)
);

CREATE TABLE upload_record (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    trigger_type     VARCHAR(20)              NOT NULL,
    status           VARCHAR(20)              NOT NULL,
    algorithm        VARCHAR(30)              NOT NULL,
    style            VARCHAR(30)              NOT NULL,
    bar_count        INTEGER,
    duration_seconds DOUBLE PRECISION,
    title            VARCHAR(200),
    description      TEXT,
    video_file       VARCHAR(255),
    youtube_video_id VARCHAR(50),
    error_message    TEXT,
    uploaded_at      TIMESTAMP WITH TIME ZONE
);

CREATE INDEX upload_record_status_idx ON upload_record (status);
CREATE INDEX upload_record_video_file_idx ON upload_record (video_file);
